from sklearn.datasets import load_iris
import pandas as pd
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score
from sklearn.inspection import DecisionBoundaryDisplay
import matplotlib.pyplot as plt

iris=load_iris()
df=pd.DataFrame(iris.data,columns=iris.feature_names)
df['target']=iris.target

df

x=iris.data[:,:2]
y=(iris.target==0).astype(int)

x_train,x_test,y_train,y_test=train_test_split(x,y,random_state=42,test_size=0.2)

scaler=StandardScaler()
x_train_scaled=scaler.fit_transform(x_train)
x_test_scaled=scaler.transform(x_test)

svm=SVC(random_state=42,kernel='linear',C=1.0)
svm.fit(x_train_scaled,y_train)
svm_predict=svm.predict(x_test_scaled)

accuracy=accuracy_score(y_test,svm_predict)
accuracy*100
print(accuracy)

def svm_display(svm,x,y):
  DecisionBoundaryDisplay.from_estimator(
        svm,
        x,
        response_method='decision_function',
        plot_method='contour',
        levels=[0],
        colors='black',
        linewidths=2,
        xlabel='sepal length (scaled)',ylabel='sepal widtth (scaled)'
    )
  plt.scatter(x[:,0],x[:,1],c=y,cmap='coolwarm',label="setosa")

  plt.scatter(svm.support_vectors_[:,0],svm.support_vectors_[:,1],facecolor='none',edgecolor='black',s=100,label='non-setosa')

  plt.title("SVM Display")
  plt.legend()
  plt.show()
svm_display(svm,x_train_scaled,y_train)