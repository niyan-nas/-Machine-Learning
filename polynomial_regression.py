import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler,PolynomialFeatures
from sklearn.metrics import mean_squared_error,r2_score
from sklearn.linear_model import LinearRegression

df=pd.read_csv("/content/auto-mpg.csv")

print(df)

x=df["displacement"].values.reshape(-1,1)
y=df["mpg"]

x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42)

scaler=StandardScaler()
x_train_scaled=scaler.fit_transform(x_train)
x_test_scaled=scaler.transform(x_test)

poly=PolynomialFeatures()
x_train_poly=poly.fit_transform(x_train_scaled)
x_test_poly=poly.transform(x_test_scaled)

polymodel=LinearRegression()
polymodel.fit(x_train_poly,y_train)
poly_pred=polymodel.predict(x_test_poly)

poly_mse=mean_squared_error(y_test,poly_pred)
poly_r2=r2_score(y_test,poly_pred)

print("poly_mse",poly_mse)
print("R2 score",poly_r2)

lnmodel=LinearRegression()
lnmodel.fit(x_train_scaled,y_train)
ln_pred=lnmodel.predict(x_test_scaled)

ln_mse=mean_squared_error(y_test,ln_pred)
ln_r2=r2_score(y_test,ln_pred)

print("poly_mse",ln_mse)
print("R2 score",ln_r2)

plt.scatter(x_test,y_test,alpha=0.6,label="Actual data",color="black")
x_grid=np.linspace(x.min(),x.max(),500).reshape(-1,1)
x_grid_scaled=scaler.transform(x_grid)
x_grid_poly=poly.transform(x_grid_scaled)

plt.plot(x_grid,polymodel.predict(x_grid_poly),color='red',label='Polynomial FIT',linewidth=2)
plt.plot(x_grid,lnmodel.predict(x_grid_scaled),color='blue',label='LN FIT',linewidth=2,linestyle='--')

plt.title='Displacement vs MPG'
plt.xlabel='Displacement'
plt.ylabel='mpg'
plt.legend()
plt.grid(True)
plt.show()