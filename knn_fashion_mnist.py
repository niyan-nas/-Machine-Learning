import numpy as np
import pandas as pd
import time

from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score
from sklearn.datasets import fetch_openml

data=fetch_openml('Fashion-MNIST',version=1,as_frame=False,parser='auto')

x=data.data[:2000]/255.0
y=data.target[:2000].astype(int)

x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=200,random_state=42)

def knn(x_train,y_train,x,k):
  distance=np.sqrt(np.sum((x_train-x)**2,axis=1))
  nearest=np.argsort(distance)[:k]
  label=y_train[nearest]
  return np.bincount(label).argmax()
for k in [3,5,7]:
  start=time.time()
  predictions=[]
  for x in x_test:
    predictions.append(knn(x_train,y_train,x,k))
  accuracy=accuracy_score(y_test,predictions)
  end=time.time()
  print("K:",k)
  print("Accuracy:",accuracy)
  print("Time:",round(end-start,2),"Seconds")