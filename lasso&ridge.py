from sklearn.datasets import load_diabetes
from sklearn.model_selection import train_test_split,GridSearchCV
from sklearn.linear_model import LinearRegression,Ridge,Lasso
from sklearn.metrics import mean_squared_error,r2_score

data=load_diabetes()
x=data.data
y=data.target

x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42)

ln=LinearRegression()
ln.fit(x_train,y_train)
ln_pred=ln.predict(x_test)

ridge=Ridge()
ridge_cv=GridSearchCV(
    ridge,{'alpha':[0.01,0.1,10,100]},cv=5
)
ridge_cv.fit(x_train,y_train)
ridge_model=ridge_cv.best_estimator_
ridge_pred=ridge_model.predict(x_test)

lesso=Lasso(max_iter=1000)
lesso_cv=GridSearchCV(
    lesso,{'alpha':[0.001,0.01,0.1]},cv=5
)
lesso_cv.fit(x_train,y_train)
lesso_model=lesso_cv.best_estimator_
lesso_pred=lesso_model.predict(x_test)

print("Best ridge alpha:",ridge_cv.best_params_['alpha'])
print("Best lasso alpha:",lesso_cv.best_params_['alpha'])

models={
    "Linear_Regression":ln_pred,
    "Ridge_Regression":ridge_pred,
    "Lasso_Regression":lesso_pred,

}
for name,pred in models.items():
  print("\n",name)
  print("MSE:",mean_squared_error(y_test,pred))
  print("R2_Score:",r2_score(y_test,pred))